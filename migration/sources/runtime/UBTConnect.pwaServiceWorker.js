var maxAttempts = 5;

function tryAddUrlToCache(cache, url) {
    function tryAdd(cache, url, attempts, resolve, reject) {
        return cache.add(url)
            .then(() => {
                trace("[install] Required resource '" + url + "' have been cached in " + CACHE_NAME);
                resolve();
            })
            .catch((err) => {
                if (attempts > 0) {
                    trace("[install] Failed to load resource '" + url + "' to cache " + CACHE_NAME + ". Attempt " + attempts);
                    return tryAdd(cache, url, attempts - 1, resolve, reject);
                }
                else {
                    trace("[install] Max attempts to load resource '" + url + "' to cache " + CACHE_NAME + " has reached. Error: " + err.message);
                    reject();
                }
            });
    }

    return new Promise((resolve, reject) => {
        return tryAdd(cache, url, maxAttempts, resolve, reject);
    });
}

self.addEventListener("install", (event) => {
    event.waitUntil(
        caches.open(CACHE_NAME)
            .then((cache) => {
                trace("[install] " + CACHE_NAME + " opened, adding all core components to cache");
                var promises = urlVersions.map(url => tryAddUrlToCache(cache, url));
                return Promise.all(promises);
            })
            .then(() => {
                trace("[install] All required resources have been cached in " + CACHE_NAME);
                return self.skipWaiting();
            })
            .catch((ex) => {
                error("[install] Error installing " + CACHE_NAME + ".", ex);
                throw ex;
            })
    );
});

self.addEventListener("fetch", (event) => {
    event.respondWith(
        caches.open(CACHE_NAME)
            .then((cache) => {
                var reqPath = new URL(event.request.url).pathname;
                var req = reqPath in urlMappings ?
                    urlMappings[reqPath] :
                    event.request

                return cache.match(req)
                    .then((response) => {
                        if (response) {
                            trace("[fetch] Returning from " + CACHE_NAME + " cache: " + reqPath);
                            return response;
                        }
                        return fetch(req)
                            .then((response) => {
                                trace("[fetch] Returning from server: " + reqPath);
                                return response;
                            })
                            .catch((ex) => error("[fetch] Error fetching " + reqPath + " from server. ", ex));
                    })
                    .catch((ex) => error("[fetch] Error fetching " + reqPath + " from " + CACHE_NAME + " cache. ", ex));
            })
            .catch((ex) => error("[fetch] Error trying to open " + CACHE_NAME + " cache. ", ex))
    );
});

self.addEventListener("activate", (event) => {
    event.waitUntil(
        caches.keys().then(keys => Promise.all(
            keys.map(key => {
                if (key && key.startsWith(MODULE_NAME) && key !== CACHE_NAME) {
                    trace("[activate] Deleting " + key + " old cache entry");
                    return caches.delete(key);
                }
            })
        )).then(() => {
            trace("[activate] " + MODULE_NAME + " was upgraded to version " + VERSION_TOKEN);
            self.clients.claim();
        })
        .catch((ex) => error("[activate] Error in " + MODULE_NAME + " activation. ", ex))
    );
});

var logger;
require({
    baseUrl: "./"
}, ['OutSystems/ClientRuntime/Logger', 'OutSystems/ClientRuntime/Communication'], function (crLogger, communication) {
    logger = crLogger; 
    logger.setPostLogsFunction(communication.postLog);
});

// Service Worker handlers must be added on the initial evaluation of the script.
// So we can't guarantee that logger will be resolved before it's called. 
// That's why we're adding this wrapper.
function trace(message) {
    if (!logger) return;
    return logger.trace("Service Worker-" + CACHE_NAME, message);
}

function error(message, ex) {
    if (!logger) return;
    return logger.error("Service Worker-" + CACHE_NAME, message + (ex ? " " + ex.toString() : ""));
}
