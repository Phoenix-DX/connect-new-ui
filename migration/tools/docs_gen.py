#!/usr/bin/env python3
"""docs_gen.py: generate the reference pages of app/docs from the migration data, so they never drift.

Usage (project root): python3 migration/tools/docs_gen.py [--out app/docs/reference]

Writes (each page starts with a "generated" banner; edit the sources, not the pages):
  stack.md          confirmed stack items, pinned dependencies, ADRs        <- migration/stack.json
  screens.md        build screens: route, folder, wave, status, flags       <- migration/board.md, migration/flags.json
  flags.md          decided feature flags: key, default, branches, routes   <- migration/flags.json
  shared-blocks.md  shared OutSystems blocks and OutSystems UI patterns with the screens that use them and whether
                    a React component carries their @os-block tag            <- migration/catalog/blocks.json
  api.md            API operations of the contract: kind, screens, mock source <- app/src/api/openapi.yaml (if present)
Names only, never data. Standard library only.
"""
import argparse
import json
import os
import re

BANNER = "<!-- GENERATED by migration/tools/docs_gen.py: do not edit; change the source and re-run. -->\n\n"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def stack_page(st):
    items = [(i["topic"], i["value"] or "(open)", i["status"]) for i in st["items"]
             if not i["key"].startswith(("osui:", "equiv:"))]
    third = [(i["key"].split(":", 1)[1], i["value"] or "(open)") for i in st["items"] if i["key"].startswith(("osui:", "equiv:"))]
    deps = sorted(st["dependencies"].items()) + [(k + " (dev)", v) for k, v in sorted(st["devDependencies"].items())]
    adrs = [(a["id"], a["title"], a["status"], (a.get("at") or "")[:10]) for a in st["adr"]]
    return (BANNER + "# Stack\n\nConfirmed by the user (Phase 4). Changing anything here is an ADR.\n\n## Items\n"
            + table(["Topic", "Choice", "Status"], items)
            + "\n## OutSystems UI patterns and third-party modules\n" + table(["Pattern / module", "How it is reproduced"], third)
            + "\n## Pinned dependencies\n" + table(["Package", "Version"], deps)
            + "\n## Architecture decision records\n" + table(["ADR", "Title", "Status", "Date"], adrs)
            + "\n" + "\n".join(f"### {a['id']}: {a['title']}\n\n- Context: {a['context']}\n- Decision: {a['decision']}\n"
                               f"- Consequences: {a['consequences']}\n" for a in st["adr"]))


def board_rows(path):
    rows = []
    for line in open(path, encoding="utf-8"):
        if not line.startswith("| ") or line.startswith("| Screen ") or line.startswith("|---"):
            continue
        c = [x.strip() for x in line.strip().strip("|").split(" | ")]
        if len(c) >= 6:
            rows.append(c)
    return rows


def screens_page(board, flags):
    by_route = {}
    for name, f in flags.items():
        if f.get("gone") or f["decision"].get("status") != "decided" or f["decision"].get("branches") == "none":
            continue
        for s in f.get("screens", []):
            by_route.setdefault(s, set()).add(f["decision"].get("key", name))
    # board columns: Screen | Route | Wave | Cx | Tier | Decision | Reason | Status | Owner
    head = ["Screen", "Route", "Folder", "Wave", "Tier", "Status", "Flags"]
    rows = [(c[0], c[1], f"`src/screens/{c[0]}/`", c[2], c[4], c[7] if len(c) > 7 else "",
             ", ".join(sorted(by_route.get(c[0], [])))) for c in board if c[5] == "build"]
    return BANNER + "# Screens\n\nEvery screen in scope, at its original OutSystems route.\n\n" + table(head, rows)


def flags_page(flags):
    rows = []
    for name, f in sorted(flags.items()):
        d = f["decision"]
        if f.get("gone") or d.get("status") != "decided" or d.get("branches") == "none":
            continue
        rows.append((d.get("key"), d.get("default"), d.get("branches"), name, ", ".join(f.get("screens", [])[:8])
                     + (" …" if len(f.get("screens", [])) > 8 else "")))
    return (BANNER + "# Feature flags\n\nRead with `useFlag` / `useFlagOn` (`src/lib/flags.ts`). `default-only`: only the "
            "default branch is built. Switch while testing with `?ff=Key:value` or `?ffpanel=1`.\n\n"
            + table(["Key", "Default", "Branches", "OutSystems source", "Screens"], rows))


def blocks_page(blocks):
    rows = []
    for name, b in sorted(blocks.items()):
        if b.get("kind") not in ("shared", "osui"):
            continue
        rows.append((f"`{name}`", b["kind"], len(b.get("liveUsers", [])), "yes" if b.get("builtAt") else "no"))
    return (BANNER + "# Shared blocks\n\nOne React component per OutSystems block, tagged `@os-block <Module.Flow.Block>`. "
            "OutSystems UI patterns live in `src/shared/osui/`.\n\n" + table(["Block", "Kind", "Screens", "Built"], rows))


def api_page(yaml_path):
    if not os.path.exists(yaml_path):
        return BANNER + "# API\n\nThe contract `src/api/openapi.yaml` is not generated yet.\n"
    text = open(yaml_path, encoding="utf-8").read()
    ops = []
    for m in re.finditer(r"^  '?(/api/[^:']+)'?:\n(.*?)(?=^  '?/api/|^\S|\Z)", text, re.S | re.M):
        body = m.group(2)
        get = lambda k: (re.search(rf"{k}:\s*(.+)", body) or [None, ""])[1].strip().strip("'\"")  # noqa: E731
        ops.append((f"`{m.group(1)}`", get("x-os-kind"), get("x-mock-source"), get("x-os-writes") or "false"))
    return (BANNER + "# API\n\nOne endpoint per OutSystems action (`POST /api/<Module>/<Action>`). Source: "
            "`src/api/openapi.yaml`; types: `npm run gen:api`.\n\n" + table(["Endpoint", "Kind", "Mock source", "Writes"], ops))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="app/docs/reference")
    ap.add_argument("--migration-dir", default="migration")
    ap.add_argument("--openapi", default="app/src/api/openapi.yaml")
    a = ap.parse_args()
    m = a.migration_dir
    st = json.load(open(os.path.join(m, "stack.json"), encoding="utf-8"))
    flags = json.load(open(os.path.join(m, "flags.json"), encoding="utf-8"))["flags"]
    blocks = json.load(open(os.path.join(m, "catalog", "blocks.json"), encoding="utf-8"))
    board = board_rows(os.path.join(m, "board.md"))
    os.makedirs(a.out, exist_ok=True)
    pages = {"stack.md": stack_page(st), "screens.md": screens_page(board, flags), "flags.md": flags_page(flags),
             "shared-blocks.md": blocks_page(blocks), "api.md": api_page(a.openapi)}
    for name, text in pages.items():
        with open(os.path.join(a.out, name), "w", encoding="utf-8") as f:
            f.write(text)
    print(f"{len(pages)} reference page(s) -> {a.out}")


if __name__ == "__main__":
    main()
