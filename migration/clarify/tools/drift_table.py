#!/usr/bin/env python3
"""drift_table.py: group the parity differences of the drift wave (decision I10-12) by OutSystems block.

    python3 migration/clarify/tools/drift_table.py [--out migration/clarify/review/drift-table.md] [Route ...]

Reads `migration/screens/<Route>/parity/<state>.json` (made by `route.py parity` / `parity_sweep.py`). For every
difference it takes the innermost `[Module.Block]` of the DOM path (the block that holds the element; "screen" when
there is none) and its kind (structure, class, text, style, pseudo, layout, position, pixel, call). Output: a table
per block (routes, states, counts per kind, one example detail) and a table per route. Exempted differences are not
counted (the reports list only unexempted ones). Standard library only; no network.
"""
import argparse
import collections
import glob
import json
import os
import re

ap = argparse.ArgumentParser()
ap.add_argument("--out", default="migration/clarify/review/drift-table.md")
ap.add_argument("routes", nargs="*")
a = ap.parse_args()

routes = a.routes or sorted(
    os.path.basename(os.path.dirname(p)) for p in glob.glob("migration/screens/*/finished.json")
)
BLOCK = re.compile(r"\[([A-Za-z0-9_]+\.[A-Za-z0-9_]+)\]")
by_block = collections.defaultdict(lambda: {"routes": set(), "states": set(), "kinds": collections.Counter(), "example": ""})
by_route = {}
for r in routes:
    per_route = collections.Counter()
    for f in sorted(glob.glob(f"migration/screens/{r}/parity/*.json")):
        state = os.path.basename(f)[:-5]
        if state.endswith(".diff") or state.startswith("_"):
            continue
        try:
            d = json.load(open(f, encoding="utf-8"))
        except (OSError, ValueError):
            continue
        diffs = d.get("diffs") or []
        if isinstance(diffs, dict):
            diffs = [x for v in diffs.values() for x in (v or [])]
        for x in diffs:
            kind = x.get("kind", "?")
            path = x.get("path", "")
            blocks = BLOCK.findall(path)
            block = blocks[-1] if blocks else ("calls" if kind == "call" else "screen")
            b = by_block[block]
            b["routes"].add(r)
            b["states"].add(state)
            b["kinds"][kind] += 1
            if not b["example"]:
                b["example"] = (x.get("detail") or "")[:140].replace("|", "/")
            per_route[kind] += 1
    if per_route:
        by_route[r] = per_route

KINDS = ["structure", "class", "attr", "text", "style", "pseudo", "layout", "position", "pixel", "call"]
lines = ["# Drift table (parity differences by block)", "",
         f"Routes read: {len(routes)}. Routes with differences: {len(by_route)}. Generated by "
         "`migration/clarify/tools/drift_table.py`.", "",
         "## By block", "", "| Block | Routes | States | " + " | ".join(KINDS) + " | Example |",
         "|---|---|---|" + "---|" * len(KINDS) + "---|"]
for block, b in sorted(by_block.items(), key=lambda kv: (-len(kv[1]["routes"]), -sum(kv[1]["kinds"].values()))):
    lines.append(f"| {block} | {len(b['routes'])}: {', '.join(sorted(b['routes']))} | {', '.join(sorted(b['states']))} | "
                 + " | ".join(str(b["kinds"].get(k, 0) or "") for k in KINDS) + f" | {b['example']} |")
lines += ["", "## By route", "", "| Route | Total | " + " | ".join(KINDS) + " |", "|---|---|" + "---|" * len(KINDS)]
for r, c in sorted(by_route.items(), key=lambda kv: -sum(kv[1].values())):
    lines.append(f"| {r} | {sum(c.values())} | " + " | ".join(str(c.get(k, 0) or "") for k in KINDS) + " |")
os.makedirs(os.path.dirname(a.out), exist_ok=True)
open(a.out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{a.out}: {len(by_block)} blocks, {len(by_route)} routes with differences")
