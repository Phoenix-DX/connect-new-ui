# ---------------------------------------------------------------- project files
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from stack import BASE_DEPS, BASE_DEV, OPTION_DEPS  # noqa: E402  (pinned baseline, used without a stack)
