#!/usr/bin/env python3
"""
scaffold_react_app.py: create the React app skeleton every screen will be built into.

Usage:
  python3 scaffold_react_app.py --survey migration/survey --shell-analysis migration/shell/analysis \
      --out app [--home /<App>/<HomeScreen>]

Creates a Vite + React 19 + TypeScript app (React Router 7, TanStack Query 5, MSW 2) with:
  - server calls typed from the API contract (src/api/openapi.yaml → npm run gen:api → callAction), one endpoint per
    OutSystems action
  - quality tooling: Vitest + Testing Library (MSW in tests), ESLint (typescript-eslint strict, type-checked) + Prettier,
    Storybook for shared blocks, `npm run ci` (contract, typecheck, lint, format, tests, build)
  - every surveyed route registered at its ORIGINAL path; a screen appears automatically when
    src/screens/<Screen>/index.tsx exists, otherwise a "not migrated" placeholder is shown
  - the original OutSystems stylesheets (src/styles/os-legacy.css) and assets (public/os-assets/)
  - the captured <body> classes and the OutSystems root containers (#reactContainer, .screen-container)
  - MSW mock API: every src/**/mocks.ts handler is registered; scenarios and latency switchable
  - helpers for the OutSystems wire format, a typed action caller and a "not captured" marker
  - device classes on <html>/<body> per viewport, learned from the captured states (src/lib/device.ts)
  - a feature flag store (src/lib/flags.ts): defaults decided by the user (flags.py export), ?ff=Name:on overrides,
    a flag panel (?ffpanel=1) so the user can switch branches while testing
  - call logging (window.__osCalls) used by call parity, a "loading" mock scenario, and an in-memory store for mutations
    (src/mocks/store.ts) so create/update/delete flows behave like the original
Safe to re-run with --update-routes to refresh the generated route list only.
"""
import argparse, base64, glob, json, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("--survey", required=True, help="folder with screens.json from survey_app.py")
ap.add_argument("--shell-analysis", help="analysis folder of a home/shell screen (styles/, facts.json)")
ap.add_argument("--out", required=True)
ap.add_argument("--home", help="route to open at /")
ap.add_argument("--update-routes", action="store_true", help="only regenerate src/app/routes.generated.ts")
ap.add_argument("--stack", help="migration/stack.json confirmed by the user (stack.py); required unless --update-routes")
ap.add_argument("--allow-unconfirmed-stack", action="store_true", help="scaffold before the stack is confirmed (not recommended)")
ap.add_argument("--states-glob", default="migration/screens/*/analysis/states.json",
                help="captured states (analyze_capture.py) used to learn the device classes per viewport")
a = ap.parse_args()

STACK = None
if not a.update_routes:
    if not a.stack and not a.allow_unconfirmed_stack:
        sys.exit("pass --stack migration/stack.json: the app is scaffolded only on a stack the user confirmed (stack.py)")
    if a.stack:
        STACK = json.load(open(a.stack, encoding="utf-8"))
        unconfirmed = [i["key"] for i in STACK["items"] if i["status"] != "confirmed"]
        if unconfirmed and not a.allow_unconfirmed_stack:
            sys.exit("stack not confirmed by the user yet: " + ", ".join(unconfirmed))
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from stack import SCAFFOLD, scaffold_ok
        chosen = {i["key"]: i["value"] for i in STACK["items"]}
        mismatch = [f"{k}: chose '{chosen.get(k)}', scaffold implements '{v}'" for k, v in SCAFFOLD.items() if not scaffold_ok(k, chosen.get(k))]
        if mismatch:
            sys.exit("this scaffold does not implement the confirmed stack; the foundation owner adapts it under an ADR:\n  " + "\n  ".join(mismatch))

survey = json.load(open(os.path.join(a.survey, "screens.json"), encoding="utf-8"))
app_name = survey["app"]
screens = survey["screens"]
OUT = a.out


def w(rel, text, overwrite=True):
    p = os.path.join(OUT, rel)
    if os.path.exists(p) and not overwrite:
        return
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(text)


# ---------------------------------------------------------------- routes
names = {}
counts = {}
for s in screens.values():
    counts[s["screen"]] = counts.get(s["screen"], 0) + 1
for key, s in screens.items():
    names[key] = s["screen"] if counts[s["screen"]] == 1 else f"{s['module']}_{s['screen']}"
ordered = sorted(screens.items(), key=lambda kv: (kv[1].get("wave") or 99, kv[1]["route"]))
home = a.home or next((s["route"] for _, s in ordered if s.get("wave") == 1), ordered[0][1]["route"] if ordered else "/")
routes_ts = ["// GENERATED by scaffold_react_app.py from the survey. Do not edit by hand; re-run with --update-routes.",
             "export interface RouteInfo { path: string; screen: string; title: string; inputs: string[]; wave: number | null; variantGroup: string | null }",
             f"export const APP = {json.dumps(app_name)};",
             f"export const HOME = {json.dumps(home)};",
             "export const ROUTES: RouteInfo[] = ["]
for key, s in ordered:
    routes_ts.append("  " + json.dumps({"path": s["route"], "screen": names[key], "title": s.get("title", ""),
                                        "inputs": s.get("inputs", []), "wave": s.get("wave"), "variantGroup": s.get("variantGroup")}) + ",")
routes_ts.append("];\n")
w("src/app/routes.generated.ts", "\n".join(routes_ts))
if a.update_routes:
    print(f"routes updated: {len(screens)}")
    sys.exit(0)

# ---------------------------------------------------------------- styles and assets
body_class, body_style, html_class = "", "", ""
asset_paths = []
css = "/* No shell analysis given: run analyze_capture.py on a home screen capture and re-run the scaffold. */\n"
if a.shell_analysis:
    facts = json.load(open(os.path.join(a.shell_analysis, "facts.json"), encoding="utf-8"))
    env = facts.get("env", {})
    body_class, html_class = env.get("bodyClass", "") or "", env.get("htmlClass", "") or ""
    body_style = re.sub(r"--viewport-height:\s*[^;]+;?", "", env.get("bodyStyle", "") or "").strip()
    assets = json.load(open(os.path.join(a.shell_analysis, "styles", "assets.json"), encoding="utf-8"))
    for path, data_url in assets.items():
        m = re.match(r"data:[^;,]*(;base64)?,(.*)", data_url, re.S)
        if not m:
            continue
        raw = base64.b64decode(m.group(2)) if m.group(1) else m.group(2).encode()
        dest = os.path.join(OUT, "public", "os-assets", path.lstrip("/"))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        open(dest, "wb").write(raw)
        asset_paths.append("/os-assets/" + path.lstrip("/"))
    bundle = open(os.path.join(a.shell_analysis, "styles", "bundle.css"), encoding="utf-8").read()
    css = re.sub(r'asset:(/[^")]+)', lambda m: "/os-assets" + m.group(1), bundle)
# Device classes per viewport, from every captured state (evidence) rather than from breakpoints guessed here.
# device and OS classes OutSystems UI derives from the viewport and the user agent (each captured viewport has its own)
DEVICE_TOKENS = {"phone", "tablet", "desktop", "portrait", "landscape", "ios", "android", "windows", "osx", "linux", "iphonex", "is-touch"}
seen_vp = {}
for sp in glob.glob(a.states_glob):
    try:
        for meta in json.load(open(sp, encoding="utf-8")).values():
            vp = meta.get("viewport")
            if not vp:
                continue
            toks = sorted(set((meta.get("bodyClass") or "").split()) & DEVICE_TOKENS)
            htoks = sorted(set((meta.get("htmlClass") or "").split()) & DEVICE_TOKENS)
            if toks or htoks:
                seen_vp[vp] = {"viewport": vp, "body": toks, "html": htoks}
    except (OSError, ValueError):
        pass
if not seen_vp and body_class:
    toks = sorted(set(body_class.split()) & DEVICE_TOKENS)
    if toks:
        seen_vp["390x844"] = {"viewport": "390x844", "body": toks, "html": sorted(set(html_class.split()) & DEVICE_TOKENS)}
w("src/lib/device-classes.json", json.dumps({
    "_note": "Generated by scaffold_react_app.py from the captured states. 'captured' wins; 'fallback' are OutSystems UI "
             "default breakpoints, used only for widths never captured: capture that viewport to confirm them.",
    "tokens": sorted(DEVICE_TOKENS),
    "captured": sorted(seen_vp.values(), key=lambda v: int(v["viewport"].split("x")[0])),
    "fallback": {"phoneMax": 700, "tabletMax": 1024}}, indent=1) + "\n")

